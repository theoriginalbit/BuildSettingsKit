import Foundation
import SwiftStructureKit

package struct CodeGenerator {
	package init() {}

	package func run(with context: Context<some DiagnosticCollector>) throws {
		let outputURL = context.outputURL
		let config = context.config

		context.diagnostics.info("Output file: \(outputURL.path())")

		if config.settings.isEmpty {
			context.diagnostics.error("Must supply at least one setting to codegen", location: config.$settings)
		}

		guard let configAccessModifier = resolveAccessModifier(
			from: config.accessModifier,
			fallingBackTo: .internal,
			diagnostics: context.diagnostics,
			location: config.$accessModifier,
		) else { throw GeneratorError.generationFailed }

		guard let typeName = resolveTypeName(from: context) else {
			// no point in generating anything if the type name is invalid
			throw GeneratorError.generationFailed
		}

		var properties: [PropertyDescriptor] = []
		for setting in config.settings {
			if let property = generateSettingProperty(setting, rootAccessModifier: configAccessModifier, with: context) {
				properties.append(property)
			}
		}

		// we may not have all the settings defined, but do partial code generation
		// anyway, then throw afterward.

		let file = SwiftFile(
			headerComment: """
			\(outputURL.lastPathComponent)
			Auto-generated by BuildSettingsKit.
			DO NOT EDIT — changes will be overwritten on the next build.
			""",
			imports: [.init("Foundation")]) {
				PlainEnumDescriptor(
					typeName,
					comment: config.comment.map(DocCommentDescriptor.init(_:)),
					accessModifier: descriptor(for: configAccessModifier)
				) { /* no cases */ } members: {
					for property in properties {
						.property(property)
					}
				}
			}

		try FileManager.default.createDirectory(
			at: outputURL.deletingLastPathComponent(),
			withIntermediateDirectories: true
		)

		let newData = file.render(indentUsing: .spaces(2))

		if let existingData = try? Data(contentsOf: outputURL), existingData == newData {
			// Content is identical, no write needed otherwise we would update the modified time
			return
		}

		try newData.write(to: outputURL, options: .atomic)

		// Abort if any diagnostic errors were prevented complete generation
		guard !context.diagnostics.hasErrors else {
			throw GeneratorError.generationFailed
		}
	}

	func resolveTypeName(from context: Context<some DiagnosticCollector>) -> String? {
		guard let typeName = context.config.typeName else {
			return "BuildSettings"
		}
		guard let identifier = Identifier(typeName) else {
			context.diagnostics.error(
				"Invalid Swift identifier: '\(typeName)'",
				location: context.config.$typeName
			)
			return nil
		}
		if !identifier.followsNamingConvention(.typeName) {
			context.diagnostics.warning(
				"Identifier does not follow type naming convention of UpperCamelCase",
				location: context.config.$typeName
			)
		}
		return identifier.value
	}

	func generateSettingProperty(
		_ setting: ConfigurationSetting,
		rootAccessModifier: AccessModifier,
		with context: Context<some DiagnosticCollector>,
	) -> PropertyDescriptor? {
		guard let identifier = resolveMemberName(for: setting, with: context),
			  let (type, expression) = resolveTypeAndValue(for: setting, with: context)
		else { return nil }
		guard let accessModifier = resolveAccessModifier(
			from: setting.accessModifier,
			fallingBackTo: rootAccessModifier,
			diagnostics: context.diagnostics,
			location: setting.$accessModifier,
		) else { return nil }
		return .let(
			identifier,
			comment: setting.comment.map(DocCommentDescriptor.init(_:)),
			accessModifier: descriptor(for: accessModifier),
			isStatic: true,
			type: typeReference(for: type),
			defaultValue: expression
		)
	}

	func resolveTypeAndValue(
		for setting: ConfigurationSetting,
		with context: Context<some DiagnosticCollector>,
	) -> (SettingType, ExpressionDescriptor)? {
		guard let type = resolveType(for: setting, diagnostics: context.diagnostics) else {
			return nil
		}
		if let value = context.environment[setting.key] {
			guard let expression = resolveExpression(value, type: type, with: context, at: setting.$key) else {
				// no need to output diagnostic, resolveExpression does it
				return nil
			}
			return (type, expression)
		}
		// There was no value in the environment, check if the config defined a default
		// and validate that it can represent the type that was defined.
		if let value = setting.default {
			guard let expression = resolveExpression(value, type: type, with: context, at: setting.$key) else {
				// no need to output diagnostic, resolveExpression does it
				return nil
			}
			return (type, expression)
		}

		context.diagnostics.error(
			"No matching key in environment: '\(setting.key)' and no default value supplied",
			location: setting.$key
		)
		return nil
	}

	func resolveMemberName(
		for setting: ConfigurationSetting,
		with context: Context<some DiagnosticCollector>,
	) -> String? {
		guard let swiftName = setting.swiftName else {
			guard let identifier = Identifier.camelCased(setting.key) else {
				context.diagnostics.error(
					"Unable to turn '\(setting.key)' into valid identifier. Please specify with swiftName.",
					location: setting.$key
				)
				return nil
			}
			return identifier.value
		}
		guard let identifier = Identifier(swiftName) else {
			context.diagnostics.error(
				"Invalid identifier: '\(swiftName)'",
				location: setting.$swiftName
			)
			return nil
		}
		if !identifier.followsNamingConvention(.memberName) {
			context.diagnostics.warning(
				"Identifier does not follow member naming convention of lowerCamelCase",
				location: setting.$swiftName
			)
		}
		return identifier.value
	}

	func resolveAccessModifier(
		from value: String?,
		fallingBackTo defaultValue: AccessModifier,
		diagnostics: some DiagnosticCollector,
		location: SourceLocation?,
	) -> AccessModifier? {
		guard let value else {
			return defaultValue
		}
		if let accessModifier = AccessModifier(rawValue: value) {
			return accessModifier
		}
		diagnostics.error("Invalid access modifier: '\(value)' falling back to '\(defaultValue.rawValue)'", location: location)
		return nil
	}

	func descriptor(for accessModifier: AccessModifier) -> AccessModifierDescriptor {
		switch accessModifier {
		case .public: .public
		case .package: .package
		case .internal: .internal
		case .fileprivate: .fileprivate
		case .private: .private
		}
	}

	func resolveType(for setting: ConfigurationSetting, diagnostics: some DiagnosticCollector) -> SettingType? {
		guard let type = SettingType(rawValue: setting.type) else {
			diagnostics.error(
				"Invalid setting type: '\(setting.type)'",
				location: setting.$type
			)
			return nil
		}
		return type
	}

	func typeReference(for settingType: SettingType) -> TypeReference {
		switch settingType {
		case .string: .string
		case .bool: .bool
		case .int: .int
		case .double: .double
		case .url: .identifier("URL")
		}
	}

	func resolveExpression(
		_ value: String,
		type: SettingType,
		with context: Context<some DiagnosticCollector>,
		at location: SourceLocation?,
	) -> ExpressionDescriptor? {
		do {
			return switch type {
			case .string: .literal(.string(value))
			case .bool: try boolLiteral(value)
			case .int: try intLiteral(value)
			case .double: try doubleLiteral(value)
			case .url: try urlLiteral(value)
			}
		} catch {
			if let expected = error.expected {
				context.diagnostics.error("Could not convert value '\(value)' to \(error.type) (expected \(expected))", location: location)
			} else {
				context.diagnostics.error("Could not convert value '\(value)' to \(error.type)", location: location)
			}
			return nil
		}
	}

	func boolLiteral(_ rawValue: String) throws(LiteralConversionError) -> ExpressionDescriptor {
		switch rawValue.lowercased() {
		case "yes", "true",  "1": return .literal(.boolean(true))
		case "no",  "false", "0": return .literal(.boolean(false))
		default:
			throw LiteralConversionError(type: "boolean", expected: "yes/true/1, or no/false/0")
		}
	}

	func intLiteral(_ rawValue: String) throws(LiteralConversionError) -> ExpressionDescriptor {
		guard let value = Int(rawValue) else {
			throw LiteralConversionError(type: "integer", expected: nil)
		}
		return .literal(.integer(value))
	}

	func doubleLiteral(_ rawValue: String) throws(LiteralConversionError) -> ExpressionDescriptor {
		guard let value = Double(rawValue) else {
			throw LiteralConversionError(type: "double", expected: nil)
		}
		return .literal(.double(value))
	}

	func urlLiteral(_ rawValue: String) throws(LiteralConversionError) -> ExpressionDescriptor {
		// Note for future self: I've never seen URL(string:) fail, but just test it anyway.
		guard URL(string: rawValue) != nil else {
			throw LiteralConversionError(type: "URL", expected: nil)
		}
		return .forcedValue(
			.functionCall(.identifier("URL"), ArgumentsList {
				Argument(label: "string", value: .literal(.string(rawValue)))
			})
		)
	}
}
