import Foundation
import SwiftStructureKit

package struct CodeGenerator {
	package init() {}

	package func run(with context: Context<some DiagnosticCollector>) throws {
		let outputURL = context.outputURL
		let config = context.config

		context.diagnostics.info("Output file: \(outputURL.path())")

		if config.settings.isEmpty {
			context.diagnostics.error("Must supply at least one setting to codegen", location: config.$settings)
		}

		let configAccessModifier = resolveAccessModifier(
			from: config.accessModifier,
			fallingBackTo: .internal,
			diagnostics: context.diagnostics,
			location: config.$accessModifier,
		)

		var properties: [PropertyDescriptor] = []
		for setting in config.settings {
			if let property = generateSettingProperty(setting, rootAccessModifier: configAccessModifier, with: context) {
				properties.append(property)
			}
		}

		guard let typeName = resolveTypeName(from: context) else {
			// no point in generating anything if the type name is invalid
			throw GeneratorError.generationFailed
		}

		// we may not have all the settings defined, but do partial code generation
		// anyway, then throw afterward.

		let date = Date.now.formatted(.iso8601)
		let file = SwiftFile(
			headerComment: """
			\(outputURL.lastPathComponent)
			Auto-generated by BuildSettingsKit on \(date).
			DO NOT EDIT — changes will be overwritten on the next build.
			""",
			imports: [.init("Foundation")]) {
				PlainEnumDescriptor(
					typeName,
					comment: config.comment.map(DocCommentDescriptor.init(_:)),
					accessModifier: descriptor(for: configAccessModifier)
				) { /* no cases */ } members: {
					for property in properties {
						.property(property)
					}
				}
			}

		try FileManager.default.createDirectory(
			at: outputURL.deletingLastPathComponent(),
			withIntermediateDirectories: true
		)
		try file.render(to: outputURL, indentUsing: .spaces(2))

		// Abort if any diagnostic errors were prevented complete generation
		guard !context.diagnostics.hasErrors else {
			throw GeneratorError.generationFailed
		}
	}

	func resolveTypeName(from context: Context<some DiagnosticCollector>) -> String? {
		guard let typeName = context.config.typeName else {
			return "BuildSettings"
		}
		guard let identifier = Identifier(typeName) else {
			context.diagnostics.error(
				"Invalid Swift identifier: '\(typeName)'",
				location: context.config.$typeName
			)
			return nil
		}
		if !identifier.followsNamingConvention(.typeName) {
			context.diagnostics.warning(
				"Identifier does not follow type naming convention of UpperCamelCase",
				location: context.config.$typeName
			)
		}
		return identifier.value
	}

	func generateSettingProperty(
		_ setting: ConfigurationSetting,
		rootAccessModifier: AccessModifier,
		with context: Context<some DiagnosticCollector>
	) -> PropertyDescriptor? {
		guard let value = context.environment[setting.key] else {
			context.diagnostics.error(
				"No matching key in environment: '\(setting.key)'",
				location: setting.$key
			)
			return nil
		}
		guard let identifier = resolveMemberName(for: setting, diagnostics: context.diagnostics) else {
			return nil
		}
		return .computed(
			identifier,
			comment: setting.comment.map(DocCommentDescriptor.init(_:)),
			accessModifier: descriptor(for: resolveAccessModifier(
				from: setting.accessModifier,
				fallingBackTo: rootAccessModifier,
				diagnostics: context.diagnostics,
				location: setting.$accessModifier,
			)),
			attributes: [],
			isStatic: true,
			type: .string,
			getterEffects: .none,
			getter: {
				.literal(.string(value))
			})
	}

	func resolveMemberName(for setting: ConfigurationSetting, diagnostics: some DiagnosticCollector) -> String? {
		guard let swiftName = setting.swiftName else {
			// assumption: keys should be simple enough to only need
			// passing through a simple transformation
			return Identifier.camelCased(setting.key)
		}
		guard let identifier = Identifier(swiftName) else {
			diagnostics.error(
				"Invalid identifier: '\(swiftName)'",
				location: setting.$swiftName
			)
			return nil
		}
		if !identifier.followsNamingConvention(.memberName) {
			diagnostics.warning(
				"Identifier does not follow member naming convention of lowerCamelCase",
				location: setting.$swiftName
			)
		}
		return identifier.value
	}

	func resolveAccessModifier(
		from value: String?,
		fallingBackTo defaultValue: AccessModifier,
		diagnostics: some DiagnosticCollector,
		location: SourceLocation?,
	) -> AccessModifier {
		guard let value else {
			return defaultValue
		}
		if let accessModifier = AccessModifier(rawValue: value) {
			return accessModifier
		}
		diagnostics.warning("Invalid access modifier: '\(value)'. Falling back to '\(defaultValue.rawValue)'.", location: location)
		return defaultValue
	}

	func descriptor(for accessModifier: AccessModifier) -> AccessModifierDescriptor {
		switch accessModifier {
		case .public: .public
		case .package: .package
		case .internal: .internal
		case .fileprivate: .fileprivate
		case .private: .private
		}
	}
}
