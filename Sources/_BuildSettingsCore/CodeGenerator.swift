import Foundation
import SwiftStructureKit

package struct CodeGenerator {
	package init() {}

	package func run(with context: Context<some DiagnosticCollector>) throws {
		let outputURL = context.outputURL
		let config = context.config

		context.diagnostics.info("Output file: \(outputURL.path())")

		if config.settings.isEmpty {
			context.diagnostics.error("Must supply at least one setting to codegen", location: config.$settings)
		}

		var properties: [PropertyDescriptor] = []
		for setting in config.settings {
			if let property = generateSettingProperty(setting, with: context) {
				properties.append(property)
			}
		}

		// we may not have all the settings defined, but do partial code generation
		// anyway, then throw afterward.

		let date = Date.now.formatted(.iso8601)
		let file = SwiftFile(
			headerComment: """
			\(outputURL.lastPathComponent)
			Auto-generated by BuildSettingsKit on \(date).
			DO NOT EDIT — changes will be overwritten on the next build.
			""",
			imports: [.init("Foundation")]) {
				PlainEnumDescriptor("BuildSettings") { /* no cases */ } members: {
					for property in properties {
						.property(property)
					}
				}
			}

		try FileManager.default.createDirectory(
			at: outputURL.deletingLastPathComponent(),
			withIntermediateDirectories: true
		)
		try file.render(to: outputURL, indentUsing: .spaces(2))
	}

	func generateSettingProperty(_ setting: ConfigurationSetting, with context: Context<some DiagnosticCollector>) -> PropertyDescriptor? {
		guard let value = context.environment[setting.key] else {
			context.diagnostics.error(
				"No matching key in environment: '\(setting.key)'",
				location: setting.$key
			)
			return nil
		}
		return .computed(
			setting.swiftName ?? "",
			comment: nil,
			accessModifier: nil,
			attributes: [],
			isStatic: true,
			type: .string,
			getterEffects: .none,
			getter: {
				.literal(.string(value))
			})
	}
}
