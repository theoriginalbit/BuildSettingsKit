	// MARK: Value/Literal conversions

    @Test func `Value conversion failure emits error`() throws {
        let yaml = """
			settings:
			  - key: RETRIES
			    type: Int
			"""

        let config = try makeConfig(from: yaml)
        let outputURL = createTempOutputURL()
        defer { try? FileManager.default.removeItem(at: outputURL.deletingLastPathComponent()) }

        let diagnostics = TestDiagnosticCollector()
        let context = CodeGenerator.Context(
            environment: ["RETRIES": "not_an_int"],
            config: config,
            outputURL: outputURL,
            diagnostics: diagnostics
        )

        #expect(throws: GeneratorError.self) {
            try CodeGenerator().run(with: context)
        }

        #expect(diagnostics.hasErrors)
        #expect(diagnostics.errors.contains { $0.message.contains("Could not convert value 'not_an_int' to integer") })
    }

	static let truths = ["yes", "true", "1", "YES", "TRUE"]
	@Test(arguments: Self.truths) func `Boolean literal conversions: truths`(_ candidate: String) throws {
		let desc = try CodeGenerator().boolLiteral(candidate)
		if case let .literal(.boolean(val)) = desc {
			#expect(val == true)
		} else {
			Issue.record("Expected .literal(.boolean(true)) for \(candidate)")
		}
	}

	static let falsehoods = ["no", "false", "0", "NO", "FALSE"]
	@Test(arguments: Self.falsehoods) func `Boolean literal conversions: falsehoods`(_ candidate: String) throws {
		let desc = try CodeGenerator().boolLiteral(candidate)
		if case let .literal(.boolean(val)) = desc {
			#expect(val == false)
		} else {
			Issue.record("Expected .literal(.boolean(false)) for \(candidate)")
		}
	}

	@Test func `Boolean literal conversions: invalid`() {
		#expect(throws: LiteralConversionError.self) {
			try CodeGenerator().boolLiteral("invalid")
		}
	}

	@Test func `Integer literal conversions`() throws {
		let generator = CodeGenerator()

		let intDesc = try generator.intLiteral("123")
		if case let .literal(.integer(val)) = intDesc {
			#expect(val == 123)
		} else {
			Issue.record("Expected .literal(.integer(123))")
		}
		#expect(throws: LiteralConversionError.self) {
			try generator.intLiteral("not-an-int")
		}
	}

	@Test func `Double literal conversions`() throws {
		let generator = CodeGenerator()

		let doubleDesc = try generator.doubleLiteral("3.1415")
		if case let .literal(.double(val)) = doubleDesc {
			#expect(val == 3.1415)
		} else {
			Issue.record("Expected .literal(.double(3.1415))")
		}
		#expect(throws: LiteralConversionError.self) {
			try generator.doubleLiteral("not-a-double")
		}
	}

	@Test func `URL literal conversions`() throws {
		let urlDesc = try CodeGenerator().urlLiteral("https://apple.com")
		if case let .raw(val) = urlDesc {
			#expect(val == #"URL(string: "https://apple.com")!"#)
		} else {
			Issue.record("Expected .raw URL")
		}
		// Note for future self: it's nearly impossible to fail URL(string:)
	}
