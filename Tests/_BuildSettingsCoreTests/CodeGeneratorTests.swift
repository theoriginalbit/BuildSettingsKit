        defer { try? FileManager.default.removeItem(at: outputURL.deletingLastPathComponent()) }

        let diagnostics = TestDiagnosticCollector()
        let context = CodeGenerator.Context(
            environment: [:],
            config: config,
            outputURL: outputURL,
