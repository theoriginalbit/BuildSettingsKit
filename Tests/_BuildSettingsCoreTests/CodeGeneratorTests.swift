@testable import _BuildSettingsCore

@Suite struct CodeGeneratorTests {
    private func createTempOutputURL() -> URL {
        URL.temporaryDirectory
            .appending(path: UUID().uuidString, directoryHint: .isDirectory)
            .appending(path: "BuildSettings.swift")
    }

    private func makeConfig(from yaml: String) throws -> Configuration {
        let tempFile = URL.temporaryDirectory
            .appending(path: "\(UUID().uuidString).yaml")
        try yaml.write(to: tempFile, atomically: true, encoding: .utf8)
        defer { try? FileManager.default.removeItem(at: tempFile) }
        return try ConfigLoader.load(from: tempFile)
    }

    @Test func `Successful code generation with all supported types`() throws {
        let yaml = """
			typeName: AppSettings
			accessModifier: public
			comment: App configuration settings

			settings:
			  - key: APP_NAME
			    type: String
			    comment: The application title
			  - key: ENABLE_FEATURE
			    type: Bool
			  - key: MAX_RETRIES
			    type: Int
			  - key: TIMEOUT_SECONDS
			    type: Double
			  - key: BASE_URL
			    type: URL
			    swiftName: apiEndpoint
			    accessModifier: internal
			"""

        let config = try makeConfig(from: yaml)
        let outputURL = createTempOutputURL()
        defer { try? FileManager.default.removeItem(at: outputURL.deletingLastPathComponent()) }

        let env: [String: String] = [
            "APP_NAME": "MyAwesomeApp",
            "ENABLE_FEATURE": "yes",
            "MAX_RETRIES": "5",
            "TIMEOUT_SECONDS": "12.5",
            "BASE_URL": "https://api.example.com",
        ]

        let diagnostics = TestDiagnosticCollector()
        let context = CodeGenerator.Context(
            environment: env,
            config: config,
            outputURL: outputURL,
            diagnostics: diagnostics
        )

        try CodeGenerator().run(with: context)

        #expect(!diagnostics.hasErrors)
        #expect(FileManager.default.fileExists(atPath: outputURL.path()))

        let generatedSwift = try String(contentsOf: outputURL, encoding: .utf8)
		let expected = """
			//
			// BuildSettings.swift
			// Auto-generated by BuildSettingsKit.
			// DO NOT EDIT — changes will be overwritten on the next build.
			//

			import Foundation

			/// App configuration settings
			public enum AppSettings {
			  /// The application title
			  public static var appName: String {
			    "MyAwesomeApp"
			  }

			  public static var enableFeature: Bool {
			    true
			  }

			  public static var maxRetries: Int {
			    5
			  }

			  public static var timeoutSeconds: Double {
			    12.5
			  }

			  internal static var apiEndpoint: URL {
			    URL(string: "https://api.example.com")!
			  }
			}

			"""
        #expect(generatedSwift == expected)
    }

